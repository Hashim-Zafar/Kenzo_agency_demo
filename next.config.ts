import { withSentryConfig } from "@sentry/nextjs/config";
import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  /* config options here */
  cacheComponents: true,
  partialPrefetching: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

/**
 * Sentry: errors only. Source maps are uploaded only when SENTRY_AUTH_TOKEN,
 * SENTRY_ORG and SENTRY_PROJECT are set (e.g. in the deploy environment);
 * without them the build still works, just with minified stack traces.
 * Events go through /monitoring on this site so ad blockers don't drop them.
 */
export default withSentryConfig(nextConfig, {
  org: process.env.SENTRY_ORG,
  project: process.env.SENTRY_PROJECT,
  authToken: process.env.SENTRY_AUTH_TOKEN,
  silent: !process.env.CI,
  tunnelRoute: "/monitoring",
  widenClientFileUpload: true,
  telemetry: false,
});
